import React, { useState, useMemo } from 'react';
import {
  Flame,
  AlertTriangle,
  CheckCircle2,
  Sparkles,
  ArrowRight,
  ArrowRightLeft,
  Scale,
  RefreshCw,
  Plus,
  TrendingDown,
  Info,
  Calendar,
  Utensils,
  Check,
  Lightbulb,
  Sliders,
  ChevronRight,
  ShieldCheck
} from 'lucide-react';
import { motion, AnimatePresence } from 'motion/react';
import { MealPlan, UserProfile, Recipe } from '../types';
import {
  analyzeDayMealPlan,
  createDemonstrationMealPlan,
  MealPlanSwapSuggestion,
  DayCalorieAnalysis
} from '../lib/mealPlanSwapEngine';
import { VoicePlayButton } from './VoicePlayButton';
import { generateSmartSwap } from '../lib/gemini';
import { playSfx, vibrate } from '../lib/sensory';
import { useTranslation } from '../contexts/LanguageContext';

interface MealPlanCalorieSwapAnalyzerProps {
  mealPlan?: MealPlan;
  profile?: UserProfile | null;
  onUpdatePlan?: (day: string, mealName: string, recipeId: string | null, recipeObj?: Recipe) => void;
  onOpenInComparator?: (foodA: string, foodB: string) => void;
  onAwardPoints?: (amount: number, reason: string) => void;
  onExploreInDiscover?: (food: string) => void;
}

const DEFAULT_DAYS = [
  'Segunda-feira',
  'Terça-feira',
  'Quarta-feira',
  'Quinta-feira',
  'Sexta-feira',
  'Sábado',
  'Domingo'
];

export function MealPlanCalorieSwapAnalyzer({
  mealPlan,
  profile,
  onUpdatePlan,
  onOpenInComparator,
  onAwardPoints,
  onExploreInDiscover
}: MealPlanCalorieSwapAnalyzerProps) {
  const { t } = useTranslation();
  // Determine available days
  const availableDays = useMemo(() => {
    const keys = Object.keys(mealPlan || {});
    if (keys.length > 0) {
      // Prioritize standard days order if present
      const sorted = [...keys].sort((a, b) => {
        const idxA = DEFAULT_DAYS.indexOf(a);
        const idxB = DEFAULT_DAYS.indexOf(b);
        if (idxA !== -1 && idxB !== -1) return idxA - idxB;
        if (idxA !== -1) return -1;
        if (idxB !== -1) return 1;
        return a.localeCompare(b);
      });
      return sorted;
    }
    return DEFAULT_DAYS;
  }, [mealPlan]);

  const [selectedDay, setSelectedDay] = useState<string>(availableDays[0] || 'Segunda-feira');

  // Calorie limit configuration (defaults to profile masterPlan or 2000 kcal)
  const defaultTargetLimit = profile?.masterPlan?.dailyCalories || 2000;
  const [calorieLimit, setCalorieLimit] = useState<number>(defaultTargetLimit);
  const [isCustomLimitOpen, setIsCustomLimitOpen] = useState(false);

  // Applied swaps tracked locally for instant visual feedback and projected simulation
  const [appliedSwapIds, setAppliedSwapIds] = useState<Set<string>>(new Set());

  // Demo meal plan state if user has no meals yet
  const [demoPlanActive, setDemoPlanActive] = useState(false);

  // Dynamic AI Swap generator state
  const [aiGeneratingMeal, setAiGeneratingMeal] = useState<string | null>(null);
  const [customAiSwaps, setCustomAiSwaps] = useState<MealPlanSwapSuggestion[]>([]);

  // Resolve current active meal plan data (user's or demo)
  const activeMealPlan = useMemo(() => {
    if (demoPlanActive) {
      return createDemonstrationMealPlan();
    }
    return mealPlan || {};
  }, [demoPlanActive, mealPlan]);

  // Current day's analysis
  const dayPlanData = activeMealPlan[selectedDay] || null;
  const analysis: DayCalorieAnalysis = useMemo(() => {
    return analyzeDayMealPlan(selectedDay, dayPlanData, calorieLimit, profile);
  }, [selectedDay, dayPlanData, calorieLimit, profile]);

  // Combined suggestions (curated + dynamically generated by AI)
  const allSuggestions = useMemo(() => {
    const currentDayAi = customAiSwaps.filter((s) => s.day === selectedDay);
    return [...currentDayAi, ...analysis.suggestions];
  }, [analysis.suggestions, customAiSwaps, selectedDay]);

  // Compute projected calories with applied swaps
  const totalSavingsApplied = useMemo(() => {
    return allSuggestions
      .filter((s) => appliedSwapIds.has(s.id))
      .reduce((acc, curr) => acc + curr.calorieSavings, 0);
  }, [allSuggestions, appliedSwapIds]);

  const projectedCalories = Math.max(0, analysis.totalCalories - totalSavingsApplied);
  const projectedDifference = projectedCalories - calorieLimit;
  const projectedIsOver = projectedCalories > calorieLimit;

  // Toggle apply swap to plan
  const handleApplySwap = (swap: MealPlanSwapSuggestion) => {
    playSfx('success');
    vibrate(40);

    const newSet = new Set(appliedSwapIds);
    const isNowApplied = !newSet.has(swap.id);

    if (isNowApplied) {
      newSet.add(swap.id);
      if (onAwardPoints) {
        onAwardPoints(35, `Troca saudável aplicada no plano: ${swap.substituteFood}`);
      }

      // If user has a real meal plan and onUpdatePlan callback, update the recipe
      if (onUpdatePlan && dayPlanData?.meals) {
        const currentMeal = (dayPlanData.meals as any)[swap.mealType];
        if (currentMeal) {
          const updatedRecipe: Recipe = {
            ...currentMeal,
            name: `${currentMeal.name} (c/ ${swap.substituteFood})`,
            description: `${currentMeal.description || ''} • [Substituição Inteligente: ${swap.originalFood} ➔ ${swap.substituteFood}]. ${swap.reason}`,
            nutrition: {
              ...currentMeal.nutrition,
              calories: Math.max(50, (currentMeal.nutrition?.calories || currentMeal.calories || swap.caloriesOriginal) - swap.calorieSavings)
            }
          };
          onUpdatePlan(selectedDay, swap.mealType, updatedRecipe.id, updatedRecipe);
        }
      }
    } else {
      newSet.delete(swap.id);
    }

    setAppliedSwapIds(newSet);
  };

  // Generate dynamic AI swap for a specific meal
  const handleGenerateAiSwapForMeal = async (mealType: string, recipeName?: string) => {
    const targetFood = recipeName || mealType;
    setAiGeneratingMeal(mealType);
    playSfx('tap');

    try {
      const result = await generateSmartSwap(targetFood, profile);
      if (result) {
        const newSwap: MealPlanSwapSuggestion = {
          id: `ai-swap-${selectedDay}-${mealType}-${Date.now()}`,
          day: selectedDay,
          mealType,
          mealLabel: mealType.toUpperCase(),
          originalFood: result.original,
          substituteFood: result.substitute,
          caloriesOriginal: 220,
          caloriesSubstitute: 80,
          calorieSavings: 140,
          reason: result.reason,
          benefits: result.benefits,
          culinaryTip: 'Preparo otimizado pela inteligência artificial com foco em saciedade e redução calórica.',
          assistantMessage: result.assistantMessage,
          applied: false
        };

        setCustomAiSwaps((prev) => [newSwap, ...prev]);
        if (onAwardPoints) {
          onAwardPoints(20, `Nova sugestão de troca inteligente gerada para: ${targetFood}`);
        }
      }
    } catch (err) {
      console.warn('Erro ao gerar troca com IA:', err);
    } finally {
      setAiGeneratingMeal(null);
    }
  };

  return (
    <div className="space-y-8 animate-in fade-in duration-500">
      {/* Top Banner & Strategy Header */}
      <div className="clay-card p-6 md:p-8 space-y-6">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 border-b border-slate-200/60 dark:border-slate-700/60 pb-6">
          <div className="flex items-center gap-3.5">
            <div className="w-12 h-12 rounded-2xl bg-gradient-to-tr from-rose-500 to-amber-500 text-white flex items-center justify-center shadow-lg shadow-rose-500/20">
              <TrendingDown className="w-6 h-6" />
            </div>
            <div>
              <h3 className="font-serif text-2xl md:text-3xl font-bold text-slate-800 dark:text-slate-100">
                {t('calorie_optimizer', 'Otimizador de Limite Calórico')}
              </h3>
              <p className="text-sm text-slate-500 dark:text-slate-400">
                {t('calorie_optimizer_desc', 'Auditoria automática do plano alimentar com micro-trocas inteligentes para manter você dentro da meta.')}
              </p>
            </div>
          </div>

          {/* Calorie Limit Badge & Controls */}
          <div className="flex items-center gap-2">
            <div className="px-4 py-2.5 rounded-2xl bg-slate-100 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 flex items-center gap-2.5 shadow-sm">
              <Flame className="w-4 h-4 text-amber-500" />
              <div className="text-left">
                <span className="text-[10px] font-bold uppercase tracking-wider text-slate-400 block leading-tight">
                  {t('calorie_limit', 'Limite Diário')}
                </span>
                <span className="text-sm font-black font-mono text-slate-800 dark:text-slate-100">
                  {calorieLimit} kcal
                </span>
              </div>
            </div>

            <button
              onClick={() => setIsCustomLimitOpen(!isCustomLimitOpen)}
              className="p-2.5 rounded-2xl bg-white dark:bg-slate-800 border border-slate-200 dark:border-slate-700 text-slate-600 dark:text-slate-300 hover:text-emerald-600 dark:hover:text-emerald-400 transition-all shadow-sm"
              title={t('adjust_calorie_limit', 'Ajustar limite calórico')}
            >
              <Sliders className="w-4 h-4" />
            </button>
          </div>
        </div>

        {/* Collapsible Calorie Limit Slider & Presets */}
        <AnimatePresence>
          {isCustomLimitOpen && (
            <motion.div
              initial={{ opacity: 0, height: 0 }}
              animate={{ opacity: 1, height: 'auto' }}
              exit={{ opacity: 0, height: 0 }}
              className="p-5 rounded-2xl bg-slate-50 dark:bg-slate-900/60 border border-slate-200/80 dark:border-slate-800 space-y-4"
            >
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2">
                <span className="text-xs font-bold text-slate-700 dark:text-slate-300 uppercase tracking-wider flex items-center gap-1.5">
                  <Sliders className="w-3.5 h-3.5 text-emerald-500" />
                  Definir Limite Calórico Desejado:
                </span>
                <span className="text-xs font-mono font-bold text-emerald-600 dark:text-emerald-400">
                  {calorieLimit} kcal / dia
                </span>
              </div>

              {/* Slider */}
              <input
                type="range"
                min={1400}
                max={3200}
                step={50}
                value={calorieLimit}
                onChange={(e) => setCalorieLimit(Number(e.target.value))}
                className="w-full accent-emerald-500 cursor-pointer"
              />

              {/* Quick Presets */}
              <div className="flex flex-wrap gap-2 pt-1">
                {[1600, 1800, 2000, 2200, 2400].map((preset) => (
                  <button
                    key={preset}
                    onClick={() => setCalorieLimit(preset)}
                    className={`px-3 py-1.5 rounded-xl text-xs font-bold transition-all ${
                      calorieLimit === preset
                        ? 'bg-emerald-600 text-white shadow-md'
                        : 'bg-white dark:bg-slate-800 text-slate-600 dark:text-slate-400 border border-slate-200 dark:border-slate-700 hover:bg-slate-100 dark:hover:bg-slate-700'
                    }`}
                  >
                    {preset} kcal
                  </button>
                ))}
              </div>
            </motion.div>
          )}
        </AnimatePresence>

        {/* Selector de Dias da Semana */}
        <div className="flex items-center gap-2 overflow-x-auto pb-2 scrollbar-none">
          {availableDays.map((day) => {
            const dayMeals = activeMealPlan[day]?.meals || {};
            const dayCals = Object.values(dayMeals).reduce(
              (acc: number, curr: any) => acc + (curr?.nutrition?.calories || curr?.calories || 0),
              0
            );
            const isDayOver = dayCals >= calorieLimit && dayCals > 0;
            const isSelected = selectedDay === day;

            return (
              <button
                key={day}
                onClick={() => {
                  setSelectedDay(day);
                  playSfx('pop');
                }}
                className={`px-4 py-2.5 rounded-2xl text-xs font-bold transition-all shrink-0 flex items-center gap-2 border ${
                  isSelected
                    ? 'bg-slate-900 dark:bg-white text-white dark:text-slate-900 border-slate-900 dark:border-white shadow-lg'
                    : 'bg-white dark:bg-slate-800/80 text-slate-600 dark:text-slate-300 border-slate-200 dark:border-slate-700 hover:bg-slate-100 dark:hover:bg-slate-700'
                }`}
              >
                <span>{day.split('-')[0]}</span>
                {dayCals > 0 && (
                  <span
                    className={`text-[10px] font-mono px-1.5 py-0.5 rounded-md ${
                      isDayOver
                        ? 'bg-rose-500/20 text-rose-500 font-bold'
                        : 'bg-emerald-500/20 text-emerald-600 dark:text-emerald-400 font-semibold'
                    }`}
                  >
                    {dayCals} kcal
                  </span>
                )}
              </button>
            );
          })}
        </div>

        {/* Status Callout Card */}
        {analysis.status === 'empty' ? (
          <div className="p-6 rounded-3xl bg-amber-50/70 dark:bg-amber-950/20 border border-amber-200/60 dark:border-amber-900/40 text-center space-y-4">
            <Utensils className="w-10 h-10 text-amber-500 mx-auto" />
            <div className="space-y-1">
              <h4 className="font-serif text-lg font-bold text-amber-900 dark:text-amber-200">
                Nenhum prato registrado em {selectedDay}
              </h4>
              <p className="text-xs text-amber-700 dark:text-amber-300/80 max-w-md mx-auto">
                Você ainda não adicionou refeições neste dia. Deseja carregar um plano de exemplo com calorias elevadas para experimentar as sugestões automáticas de micro-trocas?
              </p>
            </div>
            <button
              onClick={() => {
                setDemoPlanActive(true);
                playSfx('success');
              }}
              className="px-5 py-2.5 rounded-2xl bg-amber-500 hover:bg-amber-600 text-white font-bold text-xs shadow-md transition-all inline-flex items-center gap-2"
            >
              <Sparkles className="w-4 h-4" />
              Carregar Plano de Exemplo para Testar
            </button>
          </div>
        ) : (
          <div
            className={`p-6 rounded-3xl border transition-all ${
              analysis.isOverLimit
                ? 'bg-gradient-to-r from-rose-500/10 via-rose-500/5 to-transparent border-rose-300 dark:border-rose-900/60'
                : analysis.isNearLimit
                ? 'bg-gradient-to-r from-amber-500/10 via-amber-500/5 to-transparent border-amber-300 dark:border-amber-900/60'
                : 'bg-gradient-to-r from-emerald-500/10 via-emerald-500/5 to-transparent border-emerald-300 dark:border-emerald-900/60'
            }`}
          >
            <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
              <div className="flex items-start gap-3.5">
                <div
                  className={`w-11 h-11 rounded-2xl flex items-center justify-center shrink-0 ${
                    analysis.isOverLimit
                      ? 'bg-rose-500 text-white shadow-lg shadow-rose-500/30'
                      : analysis.isNearLimit
                      ? 'bg-amber-500 text-white shadow-lg shadow-amber-500/30'
                      : 'bg-emerald-500 text-white shadow-lg shadow-emerald-500/30'
                  }`}
                >
                  {analysis.isOverLimit ? (
                    <AlertTriangle className="w-5 h-5" />
                  ) : analysis.isNearLimit ? (
                    <Flame className="w-5 h-5" />
                  ) : (
                    <CheckCircle2 className="w-5 h-5" />
                  )}
                </div>

                <div className="space-y-1">
                  <div className="flex items-center gap-2">
                    <span
                      className={`text-xs font-black uppercase tracking-wider px-2 py-0.5 rounded-md ${
                        analysis.isOverLimit
                          ? 'bg-rose-500 text-white'
                          : analysis.isNearLimit
                          ? 'bg-amber-500 text-white'
                          : 'bg-emerald-500 text-white'
                      }`}
                    >
                      {analysis.isOverLimit
                        ? 'Limite Atingido'
                        : analysis.isNearLimit
                        ? 'Próximo do Limite'
                        : 'Dentro da Meta'}
                    </span>
                    <span className="text-xs font-bold text-slate-500 dark:text-slate-400">
                      • {selectedDay}
                    </span>
                  </div>

                  <h4 className="font-serif text-xl font-bold text-slate-800 dark:text-slate-100">
                    {analysis.isOverLimit
                      ? `${analysis.totalCalories} kcal ingeridas (+${analysis.difference} kcal acima da meta)`
                      : analysis.isNearLimit
                      ? `${analysis.totalCalories} kcal (${analysis.percentageOfLimit}% do limite de ${calorieLimit} kcal)`
                      : `${analysis.totalCalories} kcal de ${calorieLimit} kcal (${analysis.percentageOfLimit}%)`}
                  </h4>

                  <p className="text-xs text-slate-600 dark:text-slate-300 leading-relaxed max-w-xl">
                    {analysis.isOverLimit
                      ? 'Identificamos pratos com alta densidade energética no seu dia. Veja abaixo as pequenas trocas sugeridas para reduzir calorias sem passar fome.'
                      : analysis.isNearLimit
                      ? 'Você está perto do seu teto diário. Pequenas substituições em acompanhamentos ou molhos garantem folga calórica.'
                      : 'Seu plano está balanceado! Caso deseje acelerar seus resultados ou abrir espaço para um jantar especial, você pode aplicar as trocas abaixo.'}
                  </p>
                </div>
              </div>

              {/* Quick Summary Pill */}
              <div className="text-right shrink-0 bg-white/70 dark:bg-slate-800/80 p-3.5 rounded-2xl border border-slate-200/80 dark:border-slate-700 shadow-sm">
                <span className="text-[10px] font-bold text-slate-400 uppercase tracking-widest block">
                  Sugestões Prontas
                </span>
                <span className="text-xl font-mono font-black text-emerald-600 dark:text-emerald-400">
                  {allSuggestions.length} micro-trocas
                </span>
              </div>
            </div>

            {/* Live Impact Simulator Bar */}
            {totalSavingsApplied > 0 && (
              <div className="mt-5 pt-4 border-t border-slate-200/60 dark:border-slate-700/60 space-y-2">
                <div className="flex items-center justify-between text-xs font-bold">
                  <span className="text-emerald-700 dark:text-emerald-300 flex items-center gap-1.5">
                    <ShieldCheck className="w-4 h-4 text-emerald-500" />
                    Impacto Projetado com as Trocas Selecionadas:
                  </span>
                  <span className="font-mono text-emerald-600 dark:text-emerald-400">
                    -{totalSavingsApplied} kcal economizadas
                  </span>
                </div>

                <div className="w-full h-3 rounded-full bg-slate-200 dark:bg-slate-700 overflow-hidden flex">
                  <div
                    className="h-full bg-emerald-500 transition-all duration-500"
                    style={{
                      width: `${Math.min(100, Math.round((projectedCalories / calorieLimit) * 100))}%`
                    }}
                  />
                </div>

                <div className="flex items-center justify-between text-[11px] text-slate-500 dark:text-slate-400 font-mono">
                  <span>De {analysis.totalCalories} kcal</span>
                  <span className="font-bold text-slate-800 dark:text-slate-200">
                    ➔ Novo Total: {projectedCalories} kcal ({projectedIsOver ? `+${projectedDifference} kcal` : '✅ Dentro da meta'})
                  </span>
                  <span>Meta: {calorieLimit} kcal</span>
                </div>
              </div>
            )}
          </div>
        )}
      </div>

      {/* Meal by Meal Breakdown Cards */}
      {analysis.status !== 'empty' && (
        <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
          {analysis.mealBreakdown.map((mb) => (
            <div
              key={mb.mealType}
              className="p-4 rounded-2xl bg-white/70 dark:bg-slate-800/70 border border-slate-200/70 dark:border-slate-700/70 shadow-sm space-y-2"
            >
              <div className="flex items-center justify-between text-xs">
                <span className="font-bold text-slate-600 dark:text-slate-300">{mb.label}</span>
                <span className="font-mono text-[10px] text-slate-400">{mb.percentageOfDay}%</span>
              </div>
              <p className="text-lg font-black font-mono text-slate-800 dark:text-slate-100 leading-none">
                {mb.calories} <span className="text-xs font-normal text-slate-400">kcal</span>
              </p>
              <p className="text-[11px] text-slate-500 dark:text-slate-400 truncate" title={mb.recipeName || 'Sem receita'}>
                {mb.recipeName || 'Não configurado'}
              </p>

              <button
                onClick={() => handleGenerateAiSwapForMeal(mb.mealType, mb.recipeName)}
                disabled={aiGeneratingMeal === mb.mealType}
                className="w-full pt-1 text-[10px] font-bold text-emerald-600 dark:text-emerald-400 hover:underline flex items-center justify-center gap-1 disabled:opacity-50"
              >
                {aiGeneratingMeal === mb.mealType ? (
                  <RefreshCw className="w-3 h-3 animate-spin" />
                ) : (
                  <Sparkles className="w-3 h-3" />
                )}
                <span>Gerar Troca IA</span>
              </button>
            </div>
          ))}
        </div>
      )}

      {/* Suggested Smart Micro-Swaps List */}
      <div className="space-y-6">
        <div className="flex items-center justify-between">
          <div className="space-y-0.5">
            <h3 className="font-serif text-2xl font-bold text-slate-800 dark:text-slate-100 flex items-center gap-2">
              <Lightbulb className="w-5 h-5 text-amber-500" />
              Pequenas Trocas Saudáveis Recomendadas
            </h3>
            <p className="text-xs text-slate-500 dark:text-slate-400">
              Substituições calculadas para reduzir densidade calórica e manter volume, saciedade e sabor.
            </p>
          </div>

          <span className="text-xs font-bold text-emerald-600 dark:text-emerald-400 bg-emerald-50 dark:bg-emerald-950/40 px-3 py-1 rounded-full border border-emerald-200 dark:border-emerald-800">
            {allSuggestions.length} opções disponíveis
          </span>
        </div>

        {allSuggestions.length === 0 ? (
          <div className="clay-card p-12 text-center space-y-3">
            <CheckCircle2 className="w-12 h-12 text-emerald-500 mx-auto" />
            <h4 className="font-serif text-xl font-bold text-slate-800 dark:text-slate-200">
              Nenhuma troca necessária no momento!
            </h4>
            <p className="text-sm text-slate-500 dark:text-slate-400 max-w-md mx-auto">
              Seu plano alimentar para este dia está perfeitamente ajustado com calorias moderadas e sem ingredientes de risco.
            </p>
          </div>
        ) : (
          <div className="grid grid-cols-1 gap-5">
            {allSuggestions.map((swap) => {
              const isApplied = appliedSwapIds.has(swap.id);

              return (
                <div
                  key={swap.id}
                  className={`clay-card p-6 md:p-7 transition-all space-y-5 border-2 ${
                    isApplied
                      ? 'border-emerald-500/80 bg-emerald-500/5 shadow-lg shadow-emerald-500/10'
                      : 'border-transparent hover:border-slate-300 dark:hover:border-slate-700'
                  }`}
                >
                  {/* Top Bar with Meal Type & Calorie Savings */}
                  <div className="flex items-center justify-between gap-3 border-b border-slate-200/60 dark:border-slate-700/60 pb-3.5">
                    <div className="flex items-center gap-2">
                      <span className="text-xs font-black uppercase tracking-wider px-2.5 py-1 rounded-xl bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700">
                        {swap.mealLabel}
                      </span>
                      {isApplied && (
                        <span className="text-xs font-bold text-emerald-600 dark:text-emerald-400 flex items-center gap-1 bg-emerald-100 dark:bg-emerald-900/40 px-2.5 py-1 rounded-xl">
                          <Check className="w-3.5 h-3.5" /> Aplicada no Plano
                        </span>
                      )}
                    </div>

                    <div className="flex items-center gap-2">
                      <span className="px-3 py-1 rounded-xl bg-emerald-500 text-white font-mono font-black text-xs shadow-md shadow-emerald-500/20">
                        -{swap.calorieSavings} kcal
                      </span>
                      {swap.assistantMessage && (
                        <VoicePlayButton
                          text={swap.assistantMessage}
                          size="sm"
                          title="Ouvir conselho com a voz da Malu"
                        />
                      )}
                    </div>
                  </div>

                  {/* Foods Comparison Visual (Original vs Substitute) */}
                  <div className="grid grid-cols-1 md:grid-cols-2 gap-4 items-center">
                    {/* Alimento Original */}
                    <div className="p-4 rounded-2xl bg-rose-50/60 dark:bg-rose-950/20 border border-rose-100 dark:border-rose-900/40 space-y-1.5">
                      <div className="flex items-center justify-between">
                        <span className="text-[10px] font-bold uppercase tracking-wider text-rose-500">
                          Original no Plano
                        </span>
                        <span className="text-xs font-mono font-bold text-rose-600 dark:text-rose-400">
                          {swap.caloriesOriginal} kcal
                        </span>
                      </div>
                      <p className="font-serif text-lg font-bold text-slate-800 dark:text-slate-100">
                        {swap.originalFood}
                      </p>
                    </div>

                    {/* Alimento Substituto */}
                    <div className="p-4 rounded-2xl bg-emerald-50/70 dark:bg-emerald-950/20 border border-emerald-200 dark:border-emerald-800/40 space-y-1.5">
                      <div className="flex items-center justify-between">
                        <span className="text-[10px] font-bold uppercase tracking-wider text-emerald-600 dark:text-emerald-400">
                          Pequena Troca Saudável
                        </span>
                        <span className="text-xs font-mono font-bold text-emerald-700 dark:text-emerald-300">
                          {swap.caloriesSubstitute} kcal
                        </span>
                      </div>
                      <p className="font-serif text-lg font-bold text-emerald-700 dark:text-emerald-300">
                        {swap.substituteFood}
                      </p>
                    </div>
                  </div>

                  {/* Justification & Culinary Tip */}
                  <div className="space-y-2 text-xs">
                    <p className="text-slate-600 dark:text-slate-300 leading-relaxed font-sans">
                      <strong className="text-slate-800 dark:text-slate-100 font-semibold">Por que trocar: </strong>
                      {swap.reason}
                    </p>
                    {swap.culinaryTip && (
                      <p className="text-slate-500 dark:text-slate-400 italic bg-slate-50 dark:bg-slate-900/40 p-3 rounded-xl border border-slate-100 dark:border-slate-800">
                        💡 <strong>Dica culinária:</strong> {swap.culinaryTip}
                      </p>
                    )}
                  </div>

                  {/* Benefits pills */}
                  <div className="flex flex-wrap gap-2 pt-1">
                    {swap.benefits.map((b, idx) => (
                      <span
                        key={idx}
                        className="text-[11px] font-medium px-2.5 py-1 rounded-xl bg-slate-100 dark:bg-slate-800 text-slate-600 dark:text-slate-300 border border-slate-200 dark:border-slate-700 flex items-center gap-1.5"
                      >
                        <div className="w-1.5 h-1.5 rounded-full bg-emerald-500" />
                        {b}
                      </span>
                    ))}
                  </div>

                  {/* Action Buttons: Apply Swap / Compare A vs B */}
                  <div className="flex flex-wrap items-center justify-between gap-3 pt-3 border-t border-slate-200/60 dark:border-slate-700/60">
                    <div className="flex items-center gap-2">
                      {onOpenInComparator && (
                        <button
                          type="button"
                          onClick={() => {
                            playSfx('tap');
                            onOpenInComparator(swap.originalFood, swap.substituteFood);
                          }}
                          className="px-3.5 py-2 rounded-xl text-xs font-bold bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-200 hover:bg-slate-200 dark:hover:bg-slate-700 transition-all flex items-center gap-1.5 border border-slate-200 dark:border-slate-700"
                        >
                          <Scale className="w-3.5 h-3.5 text-emerald-500" />
                          <span>Comparar no Gráfico (A vs B)</span>
                        </button>
                      )}

                      {onExploreInDiscover && (
                        <button
                          type="button"
                          onClick={() => {
                            playSfx('tap');
                            onExploreInDiscover(swap.originalFood);
                          }}
                          className="px-3 py-2 rounded-xl text-xs font-semibold text-slate-500 hover:text-slate-800 dark:hover:text-slate-200 transition-all hidden sm:inline-flex items-center gap-1"
                        >
                          <Lightbulb className="w-3.5 h-3.5" />
                          <span>Mais Alternativas</span>
                        </button>
                      )}
                    </div>

                    <button
                      type="button"
                      onClick={() => handleApplySwap(swap)}
                      className={`px-5 py-2.5 rounded-xl font-bold text-xs transition-all flex items-center gap-2 cursor-pointer shadow-md ${
                        isApplied
                          ? 'bg-slate-200 dark:bg-slate-700 text-slate-700 dark:text-slate-200 hover:bg-slate-300 dark:hover:bg-slate-600'
                          : 'bg-gradient-to-r from-emerald-500 to-teal-600 hover:from-emerald-600 hover:to-teal-700 text-white shadow-emerald-500/20'
                      }`}
                    >
                      {isApplied ? (
                        <>
                          <Check className="w-4 h-4 text-emerald-500" />
                          <span>Troca Ativa (Desfazer)</span>
                        </>
                      ) : (
                        <>
                          <Sparkles className="w-4 h-4" />
                          <span>Aplicar Troca no Plano</span>
                        </>
                      )}
                    </button>
                  </div>
                </div>
              );
            })}
          </div>
        )}
      </div>
    </div>
  );
}
